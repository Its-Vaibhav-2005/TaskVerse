const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {TrackVerseDatabase}=require('./database.cjs');
test('Native SQLite persists habits, completions and month tabs; invalid writes do not erase data',()=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'trackverse-'));
  const file=path.join(temp,'trackverse.sqlite3');
  const habit={id:'h',name:'Read',category:'Learning',color:0,icon:0,created:'2026-10-01',weekdays:[1,2,3,4,5,6,7],checks:['2026-10-21']};
  let db=new TrackVerseDatabase(file);
  db.save([habit]); db.saveMonths(['2026-10-01','2026-11-01']); db.setTheme('dark'); db.close();
  db=new TrackVerseDatabase(file);
  assert.equal(db.getTheme(),'dark');
  assert.deepEqual(JSON.parse(JSON.stringify(db.load())),[habit]);
  assert.deepEqual(db.loadMonths(),['2026-10-01','2026-11-01']);
  assert.throws(()=>db.save([habit,habit]));
  assert.throws(()=>db.save([{...habit,checks:['invalid']} ]));
  assert.throws(()=>db.save([{...habit,checks:['2026-10-21','2026-10-21']} ]));
  assert.equal(db.load().length,1);
  assert.throws(()=>db.saveMonths(['2026-11-01','2026-11-01']));
  assert.equal(db.loadMonths().length,2);
  assert.throws(()=>db.restore({format:'trackverse',version:1,habits:[],months:['bad']}));
  assert.equal(db.load().length,1);
  db.save([]); assert.equal(db.load().length,0); db.close();
  assert.equal(fs.readFileSync(file).subarray(0,15).toString(),'SQLite format 3');
  fs.rmSync(temp,{recursive:true});
});
test('Windows rejects yesterday and future check-ins using local system dates',()=>{
  const db=new TrackVerseDatabase(':memory:');
  db.save([{id:'h',name:'Walk',category:'Wellness',color:0,icon:0,created:'2026-10-01',weekdays:[1,2,3,4,5,6,7],checks:[]}]);
  db.checkIn('h','2026-10-21',true,new Date(2026,9,21,23,59,59));
  assert.throws(()=>db.checkIn('h','2026-10-21',false,new Date(2026,9,22,0,0,0)),/Only today/);
  assert.deepEqual(db.load()[0].checks,['2026-10-21']);
  assert.throws(()=>db.checkIn('h','2026-10-23',true,new Date(2026,9,22)),/Only today/);
  db.checkIn('h','2026-10-22',true,new Date(2026,9,22));
  assert.equal(db.load()[0].checks.length,2);
  db.checkIn('h','2026-10-22',false,new Date(2026,9,22));
  assert.equal(db.load()[0].checks.length,1);
  db.setTheme('dark');assert.equal(db.getTheme(),'dark');
  db.setTheme('light');assert.equal(db.getTheme(),'light');
  assert.throws(()=>db.setTheme('bad'));
  db.close();
});
